#!/usr/bin/env node
// Regenerate the committed seed files under src/modules/<m>/data.seed.js.
//
//   node scripts/make-seeds.mjs
//
// Why seeds exist at all: every real data.js holds live customer PII and is
// gitignored, but eight modules import from it statically. A fresh clone would
// therefore fail to resolve those imports and the app would not build at all -
// before the new operator ever gets far enough to run a refresh. The seeds are
// committed placeholders with the right export surface and no data in them, so
// a clone builds, renders an obviously-empty dashboard with every module flagged
// STALE, and the first refresh overwrites them with real values.
//
// Seeds are derived from the local real data.js by structural skeletonisation:
// every leaf is replaced with a type-appropriate zero and every array is
// emptied. Only key NAMES survive, and those are already public in
// REFRESH_SPEC.md and the component code. No value of any kind is carried over,
// so this cannot leak a name, an email or a phone number.
//
// Re-run this whenever a generator's payload shape changes, so the seed keeps
// matching the exports the components import.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

// Replace every leaf with a type-appropriate zero; empty every array.
function skeletonize(v) {
  if (v === null || v === undefined) return null;
  if (Array.isArray(v)) return [];
  if (typeof v === "object") {
    const out = {};
    for (const k of Object.keys(v)) out[k] = skeletonize(v[k]);
    return out;
  }
  if (typeof v === "number") return 0;
  if (typeof v === "boolean") return false;
  return ""; // strings, everything else
}

const BANNER = (mod) => `// SEED placeholder for module ${mod} - committed, contains no data.
//
// The real src/modules/${mod}/data.js is machine-generated by the refresh and is
// gitignored because it holds live customer names, emails and phone numbers.
// This file exists only so a fresh clone resolves its imports and builds. Every
// value here is a structural zero produced by scripts/make-seeds.mjs.
//
// GENERATED_AT is explicitly null rather than absent. src/lib/freshness.js
// treats any falsy stamp as stale either way, so an un-refreshed install shows
// the STALE banner on this module instead of presenting empty numbers as if
// they were real - but declaring it keeps the bundler from warning about an
// import with no matching export, which would look like a fault on a fresh
// clone when it is in fact the designed behaviour.
//
// npm postinstall copies this to data.js when data.js is absent. The first
// refresh overwrites it. Never edit by hand.

export const GENERATED_AT = null;
`;

// Pure helpers that live in selfserved/data.js alongside the data. They are
// logic rather than data, so the seed carries them verbatim - otherwise the
// Shell's nav badge import breaks on a fresh clone.
const SELFSERVED_TAIL = `
export const ONBOARD_MIN_DAYS = 3;
export const ONBOARD_MAX_DAYS = 30;

function ageInDays(iso, today) {
  if (!iso) return null;
  const a = new Date(iso);
  const t = new Date(today);
  if (isNaN(a) || isNaN(t)) return null;
  return Math.floor((t - a) / 86400000);
}

export function isOnboardingAlert(item, today = SELFSERVED.today) {
  if (!item || !item.self_served) return false;
  const age = ageInDays(item.account_became_active, today);
  return age != null && age > ONBOARD_MIN_DAYS && age < ONBOARD_MAX_DAYS;
}

export function onboardingAlertCount(today = SELFSERVED.today) {
  return (SELFSERVED.items || []).filter((it) => isOnboardingAlert(it, today)).length;
}
`;

// Module 01 is not skeletonisable the way 03 and 04 are. Zeroing its date
// scaffolding produces WEEK_DAYS = [], and the component indexes that directly
// (WEEK_DAYS[0].dayNum in the week header, WEEK_DAYS.find(...) || WEEK_DAYS[0]
// for the selected day), so an empty week white-screens the whole app on a
// fresh install - which is the exact failure the seeds exist to prevent.
//
// The fix is not to scatter guards through the component for a state that only
// a seed can produce. It is for the seed to be structurally valid: an empty
// week is still a week. Date scaffolding is pure derivation from
// src/lib/dates.js with no HubSpot and no PII in it, so the seed derives it at
// import time. That also keeps it correct on whatever day the install happens,
// instead of freezing the seed-authoring date into the repo. Freshness still
// reports the module as stale, because GENERATED_AT is null regardless.
const BRIEFING_SEED_BODY = `
import { weekDays, longLabel, isoFor } from "../../lib/dates.js";

const _today = isoFor(new Date());
const _week = weekDays(_today);
const _emptyWeekMap = () => Object.fromEntries(_week.map((d) => [d.iso, []]));

export const TODAY_ISO = _today;
export const TODAY_LABEL = longLabel(_today);
export const REFRESHED_AT = "Never refreshed - run the briefing-daily refresh";
export const WEEK_DAYS = _week;
export const WEEK_PROSPECTS = _emptyWeekMap();
export const WEEK_OTHER_EVENTS = _emptyWeekMap();
export const LAST_WEEK_PROSPECTS = [];
export const TWO_WEEKS_AGO_PROSPECTS = [];
`;

// Same class of problem as module 01, one level down. The skeletoniser zeroes
// `pacing.target`, but a fresh install does not have a zero target - it has the
// monthly quota, with nothing earned against it yet. `earned / target` is then
// 0/0, and that NaN reaches a rendered string ("need NaN/workday"). Zeroing
// `pacing.today` has the same effect on the workday derivation.
//
// So the seed restates the two facts that are true of any install regardless of
// data: the quota is the quota, and today is today. Both are pure derivation -
// no HubSpot, no PII - and deriving the date at import time keeps the seed
// correct on whatever day someone installs rather than freezing the
// seed-authoring date into the repo.
const PERFORMANCE_TAIL = `
import { POINTS_QUOTA_PER_MONTH } from "../../config.js";

const _now = new Date();
const _pad = (n) => String(n).padStart(2, "0");
const _y = _now.getUTCFullYear();
const _m = _now.getUTCMonth();

PERFORMANCE.pacing.target = POINTS_QUOTA_PER_MONTH;
PERFORMANCE.pacing.today = \`\${_y}-\${_pad(_m + 1)}-\${_pad(_now.getUTCDate())}\`;
PERFORMANCE.pacing.dayOfMonth = _now.getUTCDate();
PERFORMANCE.pacing.daysInMonth = new Date(Date.UTC(_y, _m + 1, 0)).getUTCDate();
`;

// Same reasoning as PERFORMANCE_TAIL, for the two modules whose constants come
// from a config file rather than from the pull. The skeletoniser would zero
// `slaHours` and `target`, and both components divide by them.
const DEALS_TAIL = `
import { SLA_HOURS, MONTHLY_TARGET_EUR, POINTS_QUOTA } from "../../deals.config.js";

const _now = new Date();
const _pad = (n) => String(n).padStart(2, "0");

DEALS.slaHours = SLA_HOURS;
DEALS.target = MONTHLY_TARGET_EUR;
DEALS.pointsQuota = POINTS_QUOTA;
DEALS.todayIso = \`\${_now.getUTCFullYear()}-\${_pad(_now.getUTCMonth() + 1)}-\${_pad(_now.getUTCDate())}\`;
DEALS.monthStart = \`\${_now.getUTCFullYear()}-\${_pad(_now.getUTCMonth() + 1)}-01\`;
DEALS.monthLabel = _now.toLocaleString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });
`;

const PACING_TAIL = `
const _now = new Date();
const _pad = (n) => String(n).padStart(2, "0");

PACING.todayIso = \`\${_now.getUTCFullYear()}-\${_pad(_now.getUTCMonth() + 1)}-\${_pad(_now.getUTCDate())}\`;
PACING.monthLabel = _now.toLocaleString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });
`;

// Exports the components actually import, per module. Anything a data.js happens
// to carry but nothing imports is left out of the seed on purpose. `num` is the
// display number the banner quotes; it tracks the registry in src/lib/modules.js.
const MODULES = {
  briefing: {
    num: "02",
    keep: [],
    tail: BRIEFING_SEED_BODY,
  },
  performance: {
    num: "04",
    keep: ["PERFORMANCE", "GEO_MONTHLY", "MQL_GEO_MONTHLY", "PROGRESSION_GEO"],
    tail: PERFORMANCE_TAIL,
  },
  selfserved: {
    num: "05",
    keep: ["SELFSERVED"],
    tail: SELFSERVED_TAIL,
  },
  pacing: {
    num: "06",
    keep: ["PACING"],
    tail: PACING_TAIL,
  },
  deals: {
    num: "07",
    keep: ["DEALS"],
    tail: DEALS_TAIL,
  },
};

async function main() {
  for (const [mod, { num, keep, tail }] of Object.entries(MODULES)) {
    const real = resolve(ROOT, `src/modules/${mod}/data.js`);
    let live;
    try {
      live = await import(`${real}?t=${Date.now()}`);
    } catch {
      console.error(`skip ${mod}: no local data.js to derive a shape from`);
      continue;
    }
    let body = BANNER(num);
    for (const name of keep) {
      if (!(name in live)) {
        console.error(`skip ${mod}.${name}: not exported by the live data.js`);
        continue;
      }
      body += `\nexport const ${name} = ${JSON.stringify(skeletonize(live[name]), null, 2)};\n`;
    }
    body += tail;
    const out = resolve(ROOT, `src/modules/${mod}/data.seed.js`);
    await writeFile(out, body, "utf8");
    console.log(`wrote ${out}`);
  }
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
